export class IconLibrary {
  #icons;

  constructor(icons = ICONS) {
    this.#icons = { ...icons };
  }

  has(name) {
    return Object.hasOwn(this.#icons, name);
  }

  names() {
    return Object.keys(this.#icons);
  }

  /** Returns a SafeHtml <svg>. Unknown names fall back to "sparkles" so a typo never breaks a page. */
  render(name, className = 'pk-icon') {
    const body = this.#icons[name] ?? this.#icons.sparkles;
    return raw(
      `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`,
    );
  }

  /** Lets another project add its own icons without editing this file. */
  extend(icons) {
    return new IconLibrary({ ...this.#icons, ...icons });
  }
}
